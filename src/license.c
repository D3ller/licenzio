const struct License *find_license(const struct License licenses[],
                                   size_t count, const char *license_name) {

  size_t i;
  for (i = 0; i < count; i++) {
    if (strcmp(license_name, licenses[i].license_name) == 0) {
      return &licenses[i];
    }
  }

  return NULL;
}


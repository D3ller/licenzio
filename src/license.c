int createLicenseFile(const struct License *license) {

  FILE *out;

  out = fopen("LICENSE", "w");
  if (out == NULL) {
    perror("LICENSE");
    return -1;
  }

  printf("Creating '%s'...\n", license->license_description);
  if(fwrite(license->bytes, 1, license->size, out) != license->size) {
      perror("LICENSE");
      fclose(out);
      return -1;
  }

  fprintf(out, "\n\nGenerated by %s v%s\n%s\n", NAME, VERSION, GITHUB_URL);

  fclose(out);

  return 0;
}